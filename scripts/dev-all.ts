import { spawn, type ChildProcess } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  createPublicClient,
  createWalletClient,
  dotenv,
  generatePrivateKey,
  http,
  privateKeyToAccount,
  TRACEB3_LEDGER_ABI,
  type ActorRole,
  type Hex,
} from '../apps/api/src/services/seed-cli-deps.js';

const HARDHAT_DEV_ACCOUNT_0_KEY =
  '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80' as const;

const DEMO_ROLES: readonly ActorRole[] = [
  'ADMIN',
  'GENERATOR',
  'TRANSPORTER',
  'FACILITY',
  'AUDITOR',
] as const;

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const CONTRACTS_DIR = path.join(REPO_ROOT, 'packages', 'contracts');
const HARDHAT_CLI = path.join(
  CONTRACTS_DIR,
  'node_modules',
  'hardhat',
  'dist',
  'src',
  'cli.js',
);
const ARTIFACT_PATH = path.join(
  CONTRACTS_DIR,
  'artifacts',
  'contracts',
  'TraceB3Ledger.sol',
  'TraceB3Ledger.json',
);
const TSX_CLI = path.join(REPO_ROOT, 'node_modules', 'tsx', 'dist', 'cli.mjs');

function normalizeHexKey(raw: string | undefined): Hex | null {
  if (!raw) return null;
  const trimmed = raw.trim();
  const prefixed = trimmed.startsWith('0x') ? trimmed : `0x${trimmed}`;
  if (!/^0x[0-9a-fA-F]{64}$/.test(prefixed)) {
    return null;
  }
  return prefixed.toLowerCase() as Hex;
}

async function isRpcReady(rpcUrl: string): Promise<boolean> {
  try {
    const client = createPublicClient({ transport: http(rpcUrl) });
    await client.getChainId();
    return true;
  } catch {
    return false;
  }
}

async function waitForRpc(rpcUrl: string, timeoutMs = 30_000): Promise<number> {
  const client = createPublicClient({ transport: http(rpcUrl) });
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      return await client.getChainId();
    } catch {
      // retry
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`RPC endpoint did not become ready at ${rpcUrl}`);
}

async function waitForApiReady(apiUrl: string, timeoutMs = 30_000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${apiUrl}/readyz`);
      if (res.status === 200) {
        return;
      }
    } catch {
      // retry
    }
    await new Promise((r) => setTimeout(r, 300));
  }
  throw new Error(`API server did not become ready at ${apiUrl}/readyz`);
}

function loadOrCreateDemoWallets(envDemoPath: string): {
  wallets: Record<ActorRole, `0x${string}`>;
  keys: Record<ActorRole, Hex>;
} {
  const existing = existsSync(envDemoPath)
    ? dotenv.parse(readFileSync(envDemoPath, 'utf8'))
    : {};

  const wallets = {} as Record<ActorRole, `0x${string}`>;
  const keys = {} as Record<ActorRole, Hex>;

  for (const role of DEMO_ROLES) {
    const keyName = `DEMO_${role}_PRIVATE_KEY`;
    const privateKey =
      normalizeHexKey(existing[keyName] ?? process.env[keyName]) ??
      generatePrivateKey();
    const account = privateKeyToAccount(privateKey);
    keys[role] = privateKey;
    wallets[role] = account.address;
  }

  return { wallets, keys };
}

function writeDemoEnvFile(
  envDemoPath: string,
  meta: {
    apiUrl: string;
    rpcUrl: string;
    chainId: number;
    ledgerAddress: string;
  },
  wallets: Record<ActorRole, `0x${string}`>,
  keys: Record<ActorRole, Hex>,
): void {
  const lines = [
    '# Auto-generated by scripts/dev-all.ts (gitignored — do NOT commit)',
    `DEMO_API_URL=${meta.apiUrl}`,
    `DEMO_CHAIN_RPC_URL=${meta.rpcUrl}`,
    `DEMO_CHAIN_ID=${meta.chainId}`,
    `DEMO_LEDGER_ADDRESS=${meta.ledgerAddress}`,
  ];
  for (const role of DEMO_ROLES) {
    lines.push(`DEMO_${role}_ADDRESS=${wallets[role]}`);
    lines.push(`DEMO_${role}_PRIVATE_KEY=${keys[role]}`);
  }
  writeFileSync(envDemoPath, `${lines.join('\n')}\n`, 'utf8');
}

async function main(): Promise<void> {
  const envPath = path.join(REPO_ROOT, '.env');
  const envDemoPath = path.join(REPO_ROOT, '.env.demo');
  if (existsSync(envPath)) {
    dotenv.config({ path: envPath });
  }

  const rpcUrl = process.env.CHAIN_RPC_URL || 'http://127.0.0.1:8545';
  const port = Number(process.env.PORT || '3001');
  const apiUrl = `http://127.0.0.1:${port}`;
  const relayerKey =
    normalizeHexKey(process.env.RELAYER_PRIVATE_KEY) ?? HARDHAT_DEV_ACCOUNT_0_KEY;

  const children: ChildProcess[] = [];
  let shuttingDown = false;
  const shutdown = () => {
    if (shuttingDown) return;
    shuttingDown = true;
    for (const child of children) {
      if (!child.killed) {
        child.kill();
      }
    }
  };

  process.once('SIGINT', () => {
    shutdown();
    process.exit(0);
  });
  process.once('SIGTERM', () => {
    shutdown();
    process.exit(0);
  });

  if (!(await isRpcReady(rpcUrl))) {
    console.log('[dev:all] Starting local Hardhat node on 127.0.0.1:8545...');
    const hhProc = spawn(
      process.execPath,
      [HARDHAT_CLI, 'node', '--port', '8545', '--hostname', '127.0.0.1'],
      { cwd: CONTRACTS_DIR, stdio: ['ignore', 'pipe', 'pipe'] },
    );
    children.push(hhProc);
    hhProc.stderr?.on('data', (d) => process.stderr.write(d));
  } else {
    console.log(`[dev:all] Reusing running RPC endpoint at ${rpcUrl}`);
  }

  const chainId = await waitForRpc(rpcUrl);

  let ledgerAddress = process.env.LEDGER_ADDRESS?.trim();
  if (!ledgerAddress) {
    if (!existsSync(ARTIFACT_PATH)) {
      throw new Error(
        `Missing compiled contract artifact at ${ARTIFACT_PATH}. Run "pnpm --filter @traceb3/contracts compile" first.`,
      );
    }
    const artifact = JSON.parse(readFileSync(ARTIFACT_PATH, 'utf8')) as {
      bytecode: Hex;
    };
    const relayerAccount = privateKeyToAccount(relayerKey);
    const walletClient = createWalletClient({
      account: relayerAccount,
      transport: http(rpcUrl),
    });
    const publicClient = createPublicClient({ transport: http(rpcUrl) });
    const deployTx = await walletClient.deployContract({
      abi: TRACEB3_LEDGER_ABI,
      bytecode: artifact.bytecode,
      args: [relayerAccount.address, relayerAccount.address],
      chain: null,
    });
    const receipt = await publicClient.waitForTransactionReceipt({
      hash: deployTx,
    });
    ledgerAddress = receipt.contractAddress!;
    console.log(`[dev:all] Deployed TraceB3Ledger at ${ledgerAddress}`);
  }

  const { wallets, keys } = loadOrCreateDemoWallets(envDemoPath);
  writeDemoEnvFile(
    envDemoPath,
    { apiUrl, rpcUrl, chainId, ledgerAddress },
    wallets,
    keys,
  );

  console.log('[dev:all] Starting TRACEB3 API server...');
  const apiProc = spawn(
    process.execPath,
    [TSX_CLI, 'apps/api/src/server.ts'],
    {
      cwd: REPO_ROOT,
      stdio: 'inherit',
      env: {
        ...process.env,
        PORT: String(port),
        HOST: '127.0.0.1',
        DATABASE_URL: process.env.DATABASE_URL || 'pglite://.data/pglite',
        STORAGE_DRIVER: process.env.STORAGE_DRIVER || 'local',
        LOCAL_STORAGE_DIR: process.env.LOCAL_STORAGE_DIR || '.data/storage',
        CHAIN_RPC_URL: rpcUrl,
        CHAIN_ID: String(chainId),
        LEDGER_ADDRESS: ledgerAddress,
        RELAYER_PRIVATE_KEY: relayerKey,
        PUBLIC_VIEW_LEVEL: process.env.PUBLIC_VIEW_LEVEL || 'full',
        DEMO_MODE: 'true',
      },
    },
  );
  children.push(apiProc);

  apiProc.on('exit', (code) => {
    if (!shuttingDown) {
      console.error(`[dev:all] API process exited unexpectedly (code=${code})`);
      shutdown();
      process.exit(code ?? 1);
    }
  });

  await waitForApiReady(apiUrl);

  const seedRes = await fetch(`${apiUrl}/v1/dev/seed`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ wallets }),
  });
  if (!seedRes.ok) {
    throw new Error(`Failed to seed demo data: HTTP ${seedRes.status} ${await seedRes.text()}`);
  }
  const seedBody = (await seedRes.json()) as {
    createdOrganizations: number;
    createdMembers: number;
    onChainRegisteredCount: number;
  };

  console.log('\n==============================================================');
  console.log(' TRACEB3 Local Stack Ready');
  console.log('==============================================================');
  console.log(` API Base URL   : ${apiUrl}`);
  console.log(` Scalar Docs    : ${apiUrl}/docs`);
  console.log(` OpenAPI Spec   : ${apiUrl}/openapi.json`);
  console.log(` Readiness      : ${apiUrl}/readyz`);
  console.log(` Chain RPC      : ${rpcUrl} (chainId=${chainId})`);
  console.log(` TraceB3Ledger  : ${ledgerAddress}`);
  console.log(
    ` Seed Summary   : +${seedBody.createdOrganizations} orgs, +${seedBody.createdMembers} members, +${seedBody.onChainRegisteredCount} on-chain actors`,
  );
  console.log(` Demo Wallets   : saved to .env.demo (gitignored)`);
  for (const role of DEMO_ROLES) {
    console.log(`   - ${role.padEnd(11)}: ${wallets[role]}`);
  }
  console.log(' Next command   : pnpm demo:e2e');
  console.log(' Press Ctrl+C to stop.\n');

  await new Promise(() => {
    // Keep alive until SIGINT/SIGTERM
  });
}

main().catch((err) => {
  console.error('[dev:all] Startup failed:', err);
  process.exit(1);
});
