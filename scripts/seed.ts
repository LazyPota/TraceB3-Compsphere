import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ONCHAIN_ACTOR_ROLE_MAP, type ActorRole } from '@traceb3/core';
import dotenv from 'dotenv';
import { eq } from 'drizzle-orm';
import {
  createPublicClient,
  createWalletClient,
  defineChain,
  http,
  parseAbi,
  type Hex,
} from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
import {
  createDatabase,
  createLogger,
  loadConfig,
  members,
  seedDemoData,
} from '../apps/api/src/index.js';

const DEMO_ROLES: readonly ActorRole[] = [
  'ADMIN',
  'GENERATOR',
  'TRANSPORTER',
  'FACILITY',
  'AUDITOR',
] as const;

const OPERATIONAL_ROLE_MAP: Partial<Record<ActorRole, 1 | 2 | 3>> = {
  GENERATOR: ONCHAIN_ACTOR_ROLE_MAP.GENERATOR,
  TRANSPORTER: ONCHAIN_ACTOR_ROLE_MAP.TRANSPORTER,
  FACILITY: ONCHAIN_ACTOR_ROLE_MAP.FACILITY,
};

const REGISTER_ACTOR_ABI = parseAbi([
  'function registerActor(address wallet, uint8 role, bytes32 orgId) external',
]);

function normalizeHexKey(raw: string | undefined): Hex | null {
  if (!raw) return null;
  const trimmed = raw.trim();
  const prefixed = trimmed.startsWith('0x') ? trimmed : `0x${trimmed}`;
  if (!/^0x[0-9a-fA-F]{64}$/.test(prefixed)) {
    return null;
  }
  return prefixed.toLowerCase() as Hex;
}

interface DemoWalletBundle {
  wallets: Record<ActorRole, `0x${string}`>;
  envLines: string[];
}

function loadOrCreateDemoWallets(envDemoPath: string): DemoWalletBundle {
  const existing = existsSync(envDemoPath)
    ? dotenv.parse(readFileSync(envDemoPath, 'utf8'))
    : {};

  const wallets = {} as Record<ActorRole, `0x${string}`>;
  const envLines: string[] = [
    '# Auto-generated by scripts/seed.ts (gitignored — do NOT commit)',
  ];

  for (const role of DEMO_ROLES) {
    const keyName = `DEMO_${role}_PRIVATE_KEY`;
    const addrName = `DEMO_${role}_ADDRESS`;
    const privateKey =
      normalizeHexKey(existing[keyName] ?? process.env[keyName]) ??
      generatePrivateKey();
    const account = privateKeyToAccount(privateKey);
    wallets[role] = account.address;
    envLines.push(`${addrName}=${account.address}`);
    envLines.push(`${keyName}=${privateKey}`);
  }

  return { wallets, envLines };
}

async function main(): Promise<void> {
  const repoRoot = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '..',
  );
  const envPath = path.join(repoRoot, '.env');
  const envDemoPath = path.join(repoRoot, '.env.demo');

  if (existsSync(envPath)) {
    dotenv.config({ path: envPath });
  }

  const config = loadConfig(process.env);
  const logger = createLogger({ level: config.LOG_LEVEL, name: 'traceb3-seed' });

  const { wallets, envLines } = loadOrCreateDemoWallets(envDemoPath);
  writeFileSync(envDemoPath, `${envLines.join('\n')}\n`, 'utf8');
  logger.info({ envDemoPath }, 'Prepared demo actor wallets in .env.demo');

  const dbClient = await createDatabase(config.DATABASE_URL);
  try {
    await dbClient.migrate();
    const seeded = await seedDemoData(dbClient.db, { wallets });

    logger.info(
      {
        createdOrganizations: seeded.createdOrganizations,
        createdMembers: seeded.createdMembers,
        organizations: seeded.organizations.map((o) => ({
          code: o.code,
          orgType: o.orgType,
        })),
        members: seeded.members.map((m) => ({
          role: m.role,
          walletAddress: m.walletAddress,
          orgCode: m.orgCode,
        })),
      },
      'Database demo seed completed',
    );

    if (
      config.CHAIN_RPC_URL &&
      config.LEDGER_ADDRESS &&
      config.RELAYER_PRIVATE_KEY
    ) {
      const relayerKey = normalizeHexKey(config.RELAYER_PRIVATE_KEY);
      if (!relayerKey) {
        throw new Error('Invalid RELAYER_PRIVATE_KEY format');
      }

      const ledgerAddress = config.LEDGER_ADDRESS as `0x${string}`;
      const relayerAccount = privateKeyToAccount(relayerKey);
      const chain = defineChain({
        id: config.CHAIN_ID,
        name: `traceb3-${config.CHAIN_ID}`,
        nativeCurrency: { name: 'ETH', symbol: 'ETH', decimals: 18 },
        rpcUrls: { default: { http: [config.CHAIN_RPC_URL] } },
      });

      const publicClient = createPublicClient({
        chain,
        transport: http(config.CHAIN_RPC_URL),
      });
      const walletClient = createWalletClient({
        account: relayerAccount,
        chain,
        transport: http(config.CHAIN_RPC_URL),
      });

      for (const member of seeded.members) {
        const onChainRole = OPERATIONAL_ROLE_MAP[member.role];
        if (!onChainRole) {
          continue;
        }

        try {
          const { request } = await publicClient.simulateContract({
            address: ledgerAddress,
            abi: REGISTER_ACTOR_ABI,
            functionName: 'registerActor',
            args: [
              member.walletAddress as `0x${string}`,
              onChainRole,
              member.onChainOrgId as `0x${string}`,
            ],
            account: relayerAccount,
          });

          const txHash = await walletClient.writeContract(request);
          await publicClient.waitForTransactionReceipt({ hash: txHash });

          await dbClient.db
            .update(members)
            .set({
              onChainTxHash: txHash,
              onChainRegisteredAt: new Date(),
              updatedAt: new Date(),
            })
            .where(eq(members.id, member.id));

          logger.info(
            {
              role: member.role,
              walletAddress: member.walletAddress,
              txHash,
            },
            'Registered operational actor on-chain',
          );
        } catch (err) {
          const message = err instanceof Error ? err.message : String(err);
          if (/already\s*registered/i.test(message)) {
            logger.info(
              { role: member.role, walletAddress: member.walletAddress },
              'Operational actor already registered on-chain; skipping',
            );
            continue;
          }
          throw err;
        }
      }
    } else {
      logger.info(
        'Skipping on-chain registerActor (CHAIN_RPC_URL / LEDGER_ADDRESS / RELAYER_PRIVATE_KEY not all configured)',
      );
    }
  } finally {
    await dbClient.close();
  }
}

main().catch((err) => {
  console.error('Seed script failed:', err);
  process.exitCode = 1;
});
