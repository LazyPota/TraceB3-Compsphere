import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

interface HardhatArtifact {
  abi: unknown[];
}

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_PACKAGE_ROOT = path.resolve(SCRIPT_DIR, '..');

/**
 * Exports the compiled TraceB3Ledger ABI into exports/abi.json and exports/abi.ts.
 */
export async function exportAbi(
  packageRoot: string = DEFAULT_PACKAGE_ROOT,
): Promise<void> {
  const artifactPath = path.join(
    packageRoot,
    'artifacts',
    'contracts',
    'TraceB3Ledger.sol',
    'TraceB3Ledger.json',
  );
  const exportsDir = path.join(packageRoot, 'exports');

  const rawArtifact = await readFile(artifactPath, 'utf8');
  const artifact = JSON.parse(rawArtifact) as Partial<HardhatArtifact>;

  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Invalid ABI in artifact: ${artifactPath}`);
  }

  await mkdir(exportsDir, { recursive: true });

  const formattedAbi = JSON.stringify(artifact.abi, null, 2);
  await writeFile(
    path.join(exportsDir, 'abi.json'),
    `${formattedAbi}\n`,
    'utf8',
  );

  const tsContent = `// This file is auto-generated by scripts/export-abi.ts. Do not edit manually.\n\nexport const TRACEB3_LEDGER_ABI = ${formattedAbi} as const;\n`;
  await writeFile(path.join(exportsDir, 'abi.ts'), tsContent, 'utf8');
}

function isDirectExecution(): boolean {
  const currentFile = path.resolve(fileURLToPath(import.meta.url));
  const invokedFile = process.argv[1] ? path.resolve(process.argv[1]) : '';
  if (!invokedFile) {
    return false;
  }
  return process.platform === 'win32'
    ? currentFile.toLowerCase() === invokedFile.toLowerCase()
    : currentFile === invokedFile;
}

if (isDirectExecution()) {
  await exportAbi();
  console.log('Exported TraceB3Ledger ABI to exports/abi.json and exports/abi.ts');
}
