import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import hre from 'hardhat';
import { getAddress, isAddress } from 'viem';
import { exportAbi } from './export-abi.js';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(SCRIPT_DIR, '..');
const EXPORTS_DIR = path.join(PACKAGE_ROOT, 'exports');
const ADDRESSES_JSON_PATH = path.join(EXPORTS_DIR, 'addresses.json');
const ADDRESSES_TS_PATH = path.join(EXPORTS_DIR, 'addresses.ts');

async function readExistingAddresses(): Promise<Record<string, `0x${string}`>> {
  try {
    const raw = await readFile(ADDRESSES_JSON_PATH, 'utf8');
    const parsed = JSON.parse(raw) as Record<string, unknown>;
    const normalized: Record<string, `0x${string}`> = {};
    for (const [chainKey, value] of Object.entries(parsed)) {
      if (typeof value === 'string' && isAddress(value)) {
        normalized[chainKey] = getAddress(value);
      }
    }
    return normalized;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') {
      return {};
    }
    throw err;
  }
}

function formatAddressesTs(addresses: Record<string, `0x${string}`>): string {
  const sortedEntries = Object.entries(addresses).sort(
    ([a], [b]) => Number(a) - Number(b),
  );
  if (sortedEntries.length === 0) {
    return '// This file is auto-generated by scripts/deploy.ts. Do not edit manually.\n\nexport const LEDGER_ADDRESSES: Record<number, `0x${string}`> = {};\n';
  }
  const lines = sortedEntries.map(
    ([chainId, address]) => `  ${Number(chainId)}: '${address}',`,
  );
  return `// This file is auto-generated by scripts/deploy.ts. Do not edit manually.\n\nexport const LEDGER_ADDRESSES: Record<number, \`0x\${string}\`> = {\n${lines.join('\n')}\n};\n`;
}

async function main(): Promise<void> {
  const connection = await hre.network.create();
  try {
    const { viem } = connection;
    const publicClient = await viem.getPublicClient();
    const [deployer] = await viem.getWalletClients();

    if (!deployer) {
      throw new Error(
        `No deployer account available for network "${connection.networkName}"`,
      );
    }

    const admin = getAddress(
      process.env.ADMIN_ADDRESS || deployer.account.address,
    );
    const registrar = getAddress(
      process.env.REGISTRAR_ADDRESS || deployer.account.address,
    );

    const ledger = await viem.deployContract('TraceB3Ledger', [
      admin,
      registrar,
    ]);
    const deployedAddress = getAddress(ledger.address);
    const chainId = await publicClient.getChainId();

    await exportAbi(PACKAGE_ROOT);

    const existing = await readExistingAddresses();
    const merged: Record<string, `0x${string}`> = {
      ...existing,
      [String(chainId)]: deployedAddress,
    };

    const sortedJsonObject = Object.fromEntries(
      Object.entries(merged).sort(([a], [b]) => Number(a) - Number(b)),
    );

    await mkdir(EXPORTS_DIR, { recursive: true });
    await writeFile(
      ADDRESSES_JSON_PATH,
      `${JSON.stringify(sortedJsonObject, null, 2)}\n`,
      'utf8',
    );
    await writeFile(ADDRESSES_TS_PATH, formatAddressesTs(sortedJsonObject), 'utf8');

    console.log(
      JSON.stringify(
        {
          network: connection.networkName,
          chainId,
          contract: 'TraceB3Ledger',
          address: deployedAddress,
          admin,
          registrar,
        },
        null,
        2,
      ),
    );
  } finally {
    await connection.close();
  }
}

await main();
